-- Idempotent one-million-row load for deploy/mysql-demo/init.sql's demo_source.orders.
-- Run this against MySQL 8+ after the demo schema has been initialized.
INSERT INTO orders (id, customer_name, amount, updated_at)
SELECT
  1000 + numbers.n AS id,
  CONCAT('Benchmark Customer ', 1000 + numbers.n) AS customer_name,
  CAST(((numbers.n % 100000) + 100) / 100.00 AS DECIMAL(12,2)) AS amount,
  CURRENT_TIMESTAMP(6) AS updated_at
FROM (
  SELECT
    ones.d + tens.d * 10 + hundreds.d * 100 + thousands.d * 1000
      + ten_thousands.d * 10000 + hundred_thousands.d * 100000 AS n
  FROM
    (SELECT 0 d UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
     UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) ones
  CROSS JOIN
    (SELECT 0 d UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
     UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) tens
  CROSS JOIN
    (SELECT 0 d UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
     UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) hundreds
  CROSS JOIN
    (SELECT 0 d UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
     UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) thousands
  CROSS JOIN
    (SELECT 0 d UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
     UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) ten_thousands
  CROSS JOIN
    (SELECT 0 d UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
     UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) hundred_thousands
) AS numbers
ON DUPLICATE KEY UPDATE
  customer_name = VALUES(customer_name),
  amount = VALUES(amount),
  updated_at = CURRENT_TIMESTAMP(6);
