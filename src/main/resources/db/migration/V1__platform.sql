CREATE TABLE app_user (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, username VARCHAR(100) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role VARCHAR(20) NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE data_source (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL UNIQUE,
 jdbc_url VARCHAR(1000) NOT NULL, username VARCHAR(100) NOT NULL, encrypted_password TEXT NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'UNTESTED', last_error VARCHAR(500), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE pipeline (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL UNIQUE,
 source_id BIGINT NOT NULL, source_table VARCHAR(64) NOT NULL, watermark_column VARCHAR(64) NOT NULL,
 target_table VARCHAR(64) NOT NULL, transform_sql TEXT NOT NULL,
 cron_expression VARCHAR(100) NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'DRAFT', last_error VARCHAR(500),
 watermark DATETIME(6) NOT NULL DEFAULT '1970-01-01 00:00:00.000000',
 definition_code BIGINT, schedule_id INT,
 active_run_id BIGINT, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_pipeline_source FOREIGN KEY (source_id) REFERENCES data_source(id)
);
CREATE TABLE pipeline_run (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, pipeline_id BIGINT NOT NULL,
 status VARCHAR(30) NOT NULL, started_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 finished_at TIMESTAMP(6), lower_bound DATETIME(6) NOT NULL, upper_bound DATETIME(6) NOT NULL,
 message VARCHAR(1000), CONSTRAINT fk_run_pipeline FOREIGN KEY (pipeline_id) REFERENCES pipeline(id),
 INDEX ix_run_pipeline_time (pipeline_id, started_at)
);
CREATE TABLE data_service (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL,
 slug VARCHAR(100) NOT NULL UNIQUE, query_sql TEXT NOT NULL, max_rows INT NOT NULL,
 published BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE api_credential (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, service_id BIGINT NOT NULL, token_hash CHAR(64) NOT NULL UNIQUE,
 enabled BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_credential_service FOREIGN KEY (service_id) REFERENCES data_service(id)
);
CREATE TABLE audit_event (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, actor VARCHAR(100) NOT NULL, action VARCHAR(100) NOT NULL,
 target VARCHAR(200) NOT NULL, outcome VARCHAR(30) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), INDEX ix_audit_time (created_at)
);

